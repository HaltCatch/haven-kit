import { TestBed } from '@angular/core/testing';
import { TestKey } from '@angular/cdk/testing';
import { TestbedHarnessEnvironment } from '@angular/cdk/testing/testbed';
import { MatTreeHarness } from '@angular/material/tree/testing';
import { afterEach, beforeEach, expect, it } from 'vitest';
import { HavenTree } from '../tree';
import { setupTreeSelection, selectionNodes } from '../../../../tests/ui/tree-selection-support';
beforeEach(setupTreeSelection);
afterEach(() => TestBed.resetTestingModule());
it('uses CDK keyboard activation and distinct typed keys with multi-selection ARIA', async () => {
  const f = TestBed.createComponent(HavenTree);
  f.componentRef.setInput('nodes', selectionNodes);
  f.componentRef.setInput('multiple', true);
  f.componentRef.setInput('selectedKeys', ['child']);
  const tree = await TestbedHarnessEnvironment.loader(f).getHarness(MatTreeHarness);
  expect(await (await tree.host()).getAttribute('aria-multiselectable')).toBe('true');
  await (await tree.getNodes({ text: 'Group' }))[0]!.expand();
  const zero = await (await tree.getNodes({ text: 'Zero' }))[0]!.host();
  await zero.focus();
  await zero.sendKeys(' ');
  expect(f.componentInstance.selectedKeys()).toEqual(['child', 0]);
  await (await (await tree.getNodes({ text: 'String zero' }))[0]!.host()).click();
  expect(f.componentInstance.selectedKeys()).toEqual(['child', 0, '0']);
  expect(await zero.getAttribute('aria-selected')).toBe('true');
  await zero.sendKeys(TestKey.ENTER);
  expect(f.componentInstance.selectedKeys()).toEqual(['child', '0']);
});
it('preserves filtered/collapsed/unknown values and blocks inherited disabled, readonly and nonleaf activation', async () => {
  const f = TestBed.createComponent(HavenTree);
  f.componentRef.setInput('nodes', selectionNodes);
  f.componentRef.setInput('multiple', true);
  f.componentRef.setInput('selectedKeys', [0, 'missing', 'child']);
  f.componentRef.setInput('leafOnly', true);
  const tree = await TestbedHarnessEnvironment.loader(f).getHarness(MatTreeHarness);
  const group = (await tree.getNodes({ text: 'Group' }))[0]!;
  await (await group.host()).click();
  expect(f.componentInstance.selectedKeys()).toEqual([0, 'missing', 'child']);
  f.componentInstance.filter.set('String zero');
  await f.whenStable();
  await (await (await tree.getNodes({ text: 'String zero' }))[0]!.host()).click();
  expect(f.componentInstance.selectedKeys()).toEqual([0, 'missing', 'child', '0']);
  f.componentInstance.filter.set('');
  await f.whenStable();
  await group.expand();
  await group.collapse();
  expect(f.componentInstance.selectedKeys()).toEqual([0, 'missing', 'child', '0']);
  f.componentInstance.filter.set('Locked child');
  await f.whenStable();
  await (await (await tree.getNodes({ text: 'Locked child' }))[0]!.host()).click();
  expect(f.componentInstance.selectedKeys()).toContain('child');
  f.componentInstance.filter.set('String zero');
  f.componentRef.setInput('readonly', true);
  await f.whenStable();
  await (await (await tree.getNodes({ text: 'String zero' }))[0]!.host()).click();
  expect(f.componentInstance.selectedKeys()).toContain('0');
  f.componentRef.setInput('selectedKeys', { malformed: true });
  await f.whenStable();
  expect((f.nativeElement as HTMLElement).textContent).toContain('unknown, duplicate');
});
